// Персонализация: имя из Telegram и, для VIP-профилей (Атахан и др.), особый тон.
// persona = { name: string, vip: boolean }
export function personaLine(persona = {}) {
  const lines = [];
  if (persona.name) {
    lines.push(`Собеседника зовут ${persona.name}. Иногда обращайся по имени — естественно, не в каждой реплике.`);
  }
  if (persona.vip) {
    lines.push(
      "Это VIP-ученик ATA Academy. Тон — особенно тёплый и подбадривающий: отмечай каждый шаг вперёд, " +
        "верь в него вслух, ошибки подавай как естественную часть пути. Похвала конкретная и искренняя, без приторности.",
    );
  }
  return lines.join("\n");
}

export function topicPrompt(track, topicId, role, persona) {
  const topic = TOPICS[track]?.[topicId];
  if (!topic) return null;
  return [BASE, ROLE_CONTEXT[role] ?? ROLE_CONTEXT.student, personaLine(persona), topic.prompt]
    .filter(Boolean)
    .join("\n\n");
}

// CRM: подготовка занятия для конкретного ученика — любой предмет, любой возраст.
const AGE_STYLE = [
  [9, "ребёнок 7–9 лет: игра, короткие шаги по 3–5 минут, наглядность, много похвалы, простые слова"],
  [13, "ребёнок 10–13 лет: интерес и челлендж, мини-проекты, объяснение «зачем это нужно»"],
  [17, "подросток: уважение к самостоятельности, связь с реальной жизнью и экзаменами"],
  [59, "взрослый: практическая польза, чёткая структура, без инфантильности"],
  [200, "старший возраст: спокойный темп, крупные понятные шаги, повторение, опора на жизненный опыт, без спешки и сленга"],
];

export function ageStyle(age) {
  if (!Number.isFinite(age)) return "возраст не указан: нейтральный тон для взрослого";
  return AGE_STYLE.find(([max]) => age <= max)[1];
}

// student.recent — уже собранная строка с последними занятиями (свежие сверху).
export function crmPrompt(student, role, persona) {
  const who = role === "parent" ? "родителю, который занимается с ребёнком дома" : "репетитору";
  const age = Number.isFinite(student.age) ? `, ${student.age} лет` : "";
  return [
    BASE,
    personaLine(persona),
    `Ты помогаешь ${who}. Ученик: ${student.name}${age}. Предмет: ${student.subject}.` +
      (student.goal ? ` Цель: ${student.goal}.` : ""),
    `Подстрой формат под возраст — ${ageStyle(student.age)}.`,
    student.recent ? `Последние занятия:\n${student.recent}` : "",
    "По умолчанию предлагай план следующего занятия на 30–45 минут: цель, 3–4 этапа с временем, " +
      "одно домашнее задание и как понять, что тема усвоена. Отвечай на уточняющие вопросы. " +
      "Если предмет тебе плохо знаком — скажи об этом честно.",
  ]
    .filter(Boolean)
    .join("\n\n");
}

const LANG_NAME = { es: "испанском", en: "английском" };

// Голосовой режим: ответ строгим JSON, чтобы клиент мог отдельно показать реплику,
// исправления и озвучить только реплику. Фонетика оценивается по расшифровке Whisper:
// слова с низкой уверенностью распознавания приходят в запросе отдельным списком.
export function voicePrompt(track, topicId, role, persona) {
  const lang = track === "spanish" ? "es" : "en";
  return `${topicPrompt(track, topicId, role, persona)}

Сейчас голосовой режим: реплики пользователя — это расшифровка его речи на ${LANG_NAME[lang]}.
В сообщении могут быть «неуверенно распознанные слова» — вероятно, там проблема с произношением.
Ответь строго JSON-объектом:
{"reply": "твоя реплика на ${LANG_NAME[lang]} языке, 1–3 предложения, её озвучит голос",
 "translation": "перевод реплики на русский",
 "corrections": [{"heard": "что сказал пользователь", "correct": "как правильно", "note": "почему, одной строкой по-русски"}],
 "pronunciation": "1–2 предложения по-русски о звуках, которые стоит отработать, или пустая строка"}
corrections — только реальные ошибки, максимум 3; если ошибок нет — пустой массив.`;
}

