// Персонализация: имя из Telegram и, для VIP-профилей, особый тон.
// persona = { name: string, vip: boolean, kid?: boolean }
export function personaLine(persona = {}) {
  const lines = [];
  if (persona.name) {
    lines.push(`Собеседника зовут ${persona.name}. Иногда обращайся по имени — естественно, не в каждой реплике.`);
  }
  if (persona.vip && !persona.kid) {
    lines.push(
      "Это VIP-ученик ATA Academy. Тон — особенно тёплый и подбадривающий: отмечай каждый шаг вперёд, " +
        "верь в него вслух, ошибки подавай как естественную часть пути. Похвала конкретная и искренняя, без приторности.",
    );
  }
  return lines.join("\n");
}

// Варианты ответа — кнопки под репликой Мартины: ученик выбирает, а не придумывает.
const CHOICES_RULE = `"choices": ["2–3 коротких варианта ответа от лица ученика, до 4 слов каждый; пустой массив, если ученик должен ответить своими словами (например, перевести фразу)"]`;

// Текстовый режим языковых треков — тоже JSON, чтобы показать варианты кнопками.
// context — память об ученике (уровень, пройденные темы, урок дня) из lib/learning.mjs.
// Тема "lesson" — практика урока дня: её сценарий целиком приходит в context.
export function topicPrompt(track, topicId, role, persona, context = "") {
  const topic = TOPICS[track]?.[topicId];
  if (!topic && topicId !== "lesson") return null;
  return [BASE, LEAD, ROLE_CONTEXT[role] ?? ROLE_CONTEXT.student, personaLine(persona), context, topic?.prompt]
    .filter(Boolean)
    .join("\n\n");
}

export function textPrompt(track, topicId, role, persona, context) {
  const base = topicPrompt(track, topicId, role, persona, context);
  if (!base) return null;
  return `${base}

Ответь строго JSON-объектом:
{"reply": "твоя реплика", ${CHOICES_RULE}}`;
}

