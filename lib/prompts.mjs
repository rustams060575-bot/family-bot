function artChild(persona) {
  return persona.name
    ? `Ребёнка зовут ${persona.name}, ему 8 лет. Обращайся к нему по имени.`
    : "Собеседник — ребёнок. Обращайся к нему на «ты».";
}

function taskLine(task) {
  if (!task?.title) return "";
  return `Последнее задание, которое ты дала: «${task.title}»${task.idea ? ` — ${task.idea}` : ""}.`;
}

