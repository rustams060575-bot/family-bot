const TRANSLATE_LANGS = { uz: "узбекский", ru: "русский", es: "испанский", en: "английский" };
export const TRANSLATE_LANG_CODES = Object.keys(TRANSLATE_LANGS);

export function translatePrompt(from, to, register) {
  const tone =
    register === "business"
      ? "деловой регистр: вежливо, точно, как в официальной переписке"
      : "бытовой регистр: естественно, как говорят в жизни";
  const source = from === "auto" ? "определи исходный язык сам" : `исходный язык — ${TRANSLATE_LANGS[from]}`;
  return `Ты — переводчик ATA Translate. ${source}; переведи на ${TRANSLATE_LANGS[to]} язык. ${tone}.
Переводи смысл, а не слова. Узбекский — современная латиница.
Ответь строго JSON-объектом:
{"detected": "код исходного языка: uz | ru | es | en",
 "translation": "перевод",
 "alternatives": ["0–2 уместных альтернативных варианта"],
 "note": "одна строка по-русски, если есть важный нюанс (идиома, вежливость, двусмысленность), иначе пустая строка"}`;
}
